export type MessageKey = keyof typeof messages.en;

export function detectUiLanguage(): UiLanguage {
  const browserLanguage = globalThis.chrome?.i18n?.getUILanguage?.() || globalThis.navigator?.language || "en";
  return browserLanguage.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}

export function normalizeUiLanguagePreference(value: unknown): UiLanguagePreference {
  return value === "en" || value === "zh-CN" ? value : "auto";
}

export function resolveUiLanguage(preference: UiLanguagePreference): UiLanguage {
  return preference === "auto" ? detectUiLanguage() : preference;
}

export function translate(language: UiLanguage, key: MessageKey, values: Record<string, string | number> = {}) {
  let message: string = messages[language][key];
  for (const [name, value] of Object.entries(values)) {
    message = message.replaceAll(`{${name}}`, String(value));
  }
  return message;
}

export function interfaceLanguageItems(language: UiLanguage) {
  return [
    { value: "auto", label: translate(language, "followBrowser") },
    { value: "en", label: translate(language, "english") },
    { value: "zh-CN", label: translate(language, "simplifiedChinese") }
  ];
}
